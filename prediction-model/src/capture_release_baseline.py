"""
Capture the incumbent production baseline into a committed, diffable record.

WHY THIS EXISTS
---------------
Every claim of "the model got better" needs a fixed point to be measured against.
That point has to record not just the numbers but the exact inputs they came from,
or a later run cannot tell whether a difference came from a model change or from
the corpus, the NWP cache, or the scoring code having moved underneath it.

This writes prediction-model/data/release_baseline.md, containing:

  * the SHA-256 of the telemetry corpus the numbers were scored against
  * per-channel, per-horizon MAE for the served bundles and for persistence
  * the NWP field each number is compared to
  * an explicit note of which cells carry real skill and which are persistence

READ-ONLY. It never trains, fetches, or mutates a checkpoint. Re-running it on an
unchanged corpus and unchanged bundles must produce a byte-identical file; if it
does not, something is non-deterministic and that is itself worth knowing.

Note on the "+X%" column: it is skill against PERSISTENCE, not against NWP. Those
are different questions and conflating them is how this project previously
produced an over-claim. The NWP comparison is the separate rank column.
"""

import argparse
import hashlib
import json
import os
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.abspath(os.path.join(HERE, "..", "data"))

HORIZONS = [1, 3, 6, 12, 24]
CHANNELS = [
    ("temperature", "MAE degC"),
    ("humidity", "MAE %"),
    ("pressure", "MAE hPa"),
    ("wind_speed", "MAE m/s"),
]
NWP_REFERENCE = ["ECMWF IFS", "NOAA GFS"]


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def git(*args):
    import subprocess
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              timeout=30).stdout.strip()
    except Exception:
        return "unknown"


def skill(persist_mae, model_mae):
    if not persist_mae:
        return None
    return (persist_mae - model_mae) / persist_mae * 100.0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--benchmark", default=os.path.join(DATA, "nwp_benchmark_production.json"))
    ap.add_argument("--corpus", default=os.path.join(DATA, "weather_telemetry.csv"),
                    help="Telemetry corpus the benchmark was run against. The "
                         "recorded SHA-256 must be the corpus the scores actually "
                         "came from, or the release gate will refuse every later "
                         "comparison with CORPUS_MISMATCH.")
    ap.add_argument("--model-label", default="LNN production",
                    help="Key the model-under-test was written under in the "
                         "benchmark JSON. Hard-coding this silently produced an "
                         "EMPTY baseline -- 0 of 0 cells -- whenever a benchmark "
                         "was run with a different --label, and nothing said so.")
    ap.add_argument("--bundle-dir", default=os.path.join(DATA, "bundles"))
    ap.add_argument("--out", default=os.path.join(DATA, "release_baseline.md"))
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the file on disk differs from a fresh capture")
    args = ap.parse_args()

    if not os.path.exists(args.benchmark):
        print(f"missing benchmark results: {args.benchmark}")
        return 1
    results = json.load(open(args.benchmark, encoding="utf-8"))["results"]
    model_label = args.model_label

    corpus_sha = sha256_file(args.corpus)
    bundle_shas = {}
    for h in HORIZONS:
        ck = os.path.join(args.bundle_dir, f"h{h}", "checkpoint.pt")
        if os.path.exists(ck):
            bundle_shas[h] = sha256_file(ck)[:16]

    L = []
    L.append("# Release baseline: incumbent production model")
    L.append("")
    L.append("Generated by `prediction-model/src/capture_release_baseline.py`.")
    L.append("Regenerate whenever the served bundles change. Do not hand-edit.")
    L.append("")
    L.append(f"- captured: {datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}")
    L.append(f"- commit: `{git('rev-parse', 'HEAD')[:12]}`")
    L.append(f"- corpus: `{os.path.basename(args.corpus)}`")
    L.append(f"- corpus sha256: `{corpus_sha}`")
    L.append("- served bundles checkpoint sha256 (first 16): "
             + ", ".join(f"h{h}=`{s}`" for h, s in sorted(bundle_shas.items())))
    L.append("")

    # Where the NWP comparison data actually came from. The cache is gitignored and
    # regenerable, so its window is recorded here rather than assumed.
    cache = os.path.join(DATA, "nwp_benchmark_cache.json")
    if os.path.exists(cache):
        try:
            meta = json.load(open(cache, encoding="utf-8")).get("_meta", {})
            L.append(f"- NWP cache window: `{meta.get('start_date')}` .. `{meta.get('end_date')}`")
            L.append(f"- NWP source: {meta.get('source', 'unknown')}")
            if meta.get("licence_note"):
                L.append(f"- NWP licence note: {meta['licence_note']}")
        except (ValueError, OSError):
            pass
    L.append("")

    L.append("## Reading this table")
    L.append("")
    L.append("`skill` is MAE improvement against **persistence** on the identical")
    L.append("rows. It is not a comparison against NWP. A cell can show strong")
    L.append("skill and still be beaten by every NWP model; a cell can be nearly")
    L.append("tied with persistence and still beat all seven NWP models. Both have")
    L.append("happened here, so the two columns are reported separately.")
    L.append("")
    L.append("A skill value of about 0.0 means the residual head contributes")
    L.append("essentially nothing at that horizon and the model is *returning")
    L.append("persistence*. Those cells are not wins; they are unused capacity.")
    L.append("")

    L.append("## Scoreboard")
    L.append("")
    for var, unit in CHANNELS:
        L.append(f"### {var} ({unit})")
        L.append("")
        L.append("| horizon | model | persistence | skill vs persist | "
                 + " | ".join(NWP_REFERENCE) + " | rank |")
        L.append("|---|---|---|---|---|" + "---|" * (len(NWP_REFERENCE) + 1))
        for h in HORIZONS:
            key = f"h{h}"
            if key not in results or var not in results[key]:
                continue
            row = results[key][var]
            ours = row.get(model_label) or row.get("LNN production") or row.get("LNN (this project)")
            if not ours:
                continue
            pers = row["persistence"]["mae"]
            sk = skill(pers, ours["mae"])
            cells = []
            for ref in NWP_REFERENCE:
                r = row.get(ref)
                cells.append(f"{r['mae']:.3f}" if r else "n/a")
            scored = [x["mae"] for k, x in row.items() if x and k != "persistence"]
            rank = sorted(scored).index(ours["mae"]) + 1
            L.append(f"| +{h}h | {ours['mae']:.3f} | {pers:.3f} | {sk:+.1f}% | "
                     + " | ".join(cells) + f" | {rank}/{len(scored) + 1} |")
        L.append("")

    L.append("### rain occurrence (Brier score, lower is better)")
    L.append("")
    L.append("| horizon | model | persistence | climatology | best NWP |")
    L.append("|---|---|---|---|---|")
    for h in HORIZONS:
        key = f"h{h}"
        if key not in results or "_rain_brier" not in results[key]:
            continue
        b = results[key]["_rain_brier"]
        ours = b.get(model_label) or b.get("LNN production") or b.get("LNN (this project)")
        if not ours:
            continue
        clim = b.get("climatology (constant)")
        nwp_vals = [v for k, v in b.items()
                    if k not in (model_label, "LNN production", "LNN (this project)",
                                 "persistence", "climatology (constant)")]
        best_nwp = min(nwp_vals) if nwp_vals else None
        L.append(f"| +{h}h | {ours:.4f} | {b['persistence']:.4f} | "
                 + (f"{clim:.4f} | " if clim is not None else "n/a | ")
                 + (f"{best_nwp:.4f} |" if best_nwp is not None else "n/a |"))
    L.append("")

    # Classify, so the next person does not have to eyeball 20 numbers.
    real, dead = [], []
    for var, _unit in CHANNELS:
        for h in HORIZONS:
            key = f"h{h}"
            if key not in results or var not in results[key]:
                continue
            row = results[key][var]
            ours = row.get(model_label) or row.get("LNN production") or row.get("LNN (this project)")
            if not ours:
                continue
            sk = skill(row["persistence"]["mae"], ours["mae"])
            # 1.0% is the line. Anything under it is indistinguishable from
            # returning persistence, on this sample size.
            (real if sk is not None and sk >= 1.0 else dead).append(
                f"{var} +{h}h ({sk:+.1f}%)")
    L.append("## Where this model actually adds value")
    L.append("")
    L.append(f"Cells beating persistence by at least 1% ({len(real)} of "
             f"{len(real) + len(dead)}):")
    L.append("")
    for r in real:
        L.append(f"- {r}")
    L.append("")
    L.append(f"Cells effectively returning persistence ({len(dead)}). These are the")
    L.append("improvement targets; any real skill here is a gain that cannot")
    L.append("currently be worse than what is already served.")
    L.append("")
    for d in dead:
        L.append(f"- {d}")
    L.append("")
    L.append("---")
    L.append("")
    L.append("Any candidate must clear this table on identical rows before it is")
    L.append("considered for promotion. The paired significance rule lives in")
    L.append("`train_predictive_quality.py`; this file is the reference point, not")
    L.append("a substitute for that test.")
    L.append("")

    text = "\n".join(L)

    # A baseline with no rows is a silent failure: the script used to exit 0 with
    # "0 / 0 cells with real skill", which reads like a result. Refuse instead.
    if not any(line.startswith("| +") for line in L):
        print(f"REFUSING to write an empty baseline: no scoreboard rows were "
              f"parsed from {os.path.basename(args.benchmark)} under model label "
              f"{args.model_label!r}. Check the --benchmark path and --model-label.",
              file=sys.stderr)
        return 1

    if args.check:
        if not os.path.exists(args.out):
            print(f"MISSING: {args.out}")
            return 1
        current = open(args.out, encoding="utf-8").read()
        # The capture timestamp is the one line that legitimately changes on every
        # run. Excluding it is what makes --check a drift detector rather than an
        # alarm that always fires.
        def strip_ts(doc):
            return [ln for ln in doc.splitlines() if not ln.startswith("- captured:")]

        if strip_ts(current) == strip_ts(text):
            print(f"baseline unchanged: {args.out}")
            return 0
        print(f"DRIFT: {args.out} no longer matches a fresh capture")
        print("  Either the bundles changed (expected when releasing) or the")
        print("  corpus/scoring moved underneath an unchanged model (a defect).")
        import difflib
        diff = list(difflib.unified_diff(strip_ts(current), strip_ts(text),
                                         "on-disk", "fresh", lineterm="", n=1))
        for line in diff[:40]:
            print("   " + line)
        return 1

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"written: {args.out}")
    print(f"  corpus sha256 {corpus_sha[:16]}...")
    print(f"  cells with real skill: {len(real)} / {len(real) + len(dead)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
