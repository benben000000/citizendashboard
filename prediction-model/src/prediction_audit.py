"""
Append-only prediction audit trail.

WHY
---
The system kept no record of what it published. `mqtt_live_predictions.json` is
overwritten in place, so the only surviving evidence of a forecast is whatever a
client happened to display. That makes three questions unanswerable after the
fact: what did we publish, which artifact produced it, and was it right. It also
means a silent change in model or policy leaves no trace.

The trail is one JSON object per line, appended, never rewritten. Each record
binds a published number to the exact artifacts that produced it.

WHAT IS RECORDED, AND WHY EACH FIELD IS HERE
--------------------------------------------
  station / horizon / origin      to locate the forecast
  variables[].value               what was actually published
  variables[].producer            lln | nwp | blend | persistence -- so a
                                  reviewer can see the NWP router fired (or
                                  correctly did not)
  variables[].nwp_raw             the uncorrected model value, so a bad
                                  correction is reproducible
  variables[].nwp_corrected       what the correction produced before routing
  provenance.model                bundle, checkpoint id and its trained-at
  provenance.policy               policy version and the code commit it came from
  provenance.nwp                  source, cycle and issue time, or why it was
                                  not used (gate closed, stale, blocked)
  sensor_health                   the wind verdict for the station, so a dead
                                  anemometer is visible on the same record as
                                  the forecast it distorted

TWO HARD RULES
--------------
1. The trail must never break forecasting. Every write is guarded; a failed
   audit costs a log line, never a forecast.
2. It must never be silently lossy. If a value cannot be serialised the record
   is still written, with the field set to null -- an explicit gap beats a
   missing line.
"""

import hashlib
import json
import os
import threading
import time
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional

DEFAULT_PATH = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data", "prediction_audit.jsonl",
)

# Rotate at 32 MB, keep five generations. An append-only log that grows forever
# is its own outage.
MAX_BYTES = 32 * 1024 * 1024
KEEP_GENERATIONS = 5

SCHEMA_VERSION = 1

# Re-read provenance at most this often. The policy is regenerated by a separate
# process, so caching forever would pin a stale version into the trail.
PROVENANCE_TTL_SECONDS = 300.0


def _make_id(station_id: Any, origin_timestamp: Any, horizon_hours: Any) -> str:
    """
    Deterministic id for a forecast, so a later verification can name the exact
    line it scored. Derived rather than random: re-deriving it from the same
    inputs is how you tell a retry from a new prediction.
    """
    raw = f"{station_id}|{origin_timestamp}|{horizon_hours}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:20]


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def _finite(x: Any) -> Optional[float]:
    if x is None or isinstance(x, bool):
        return None
    try:
        f = float(x)
    except (TypeError, ValueError):
        return None
    return f if f == f and abs(f) != float("inf") else None


def _policy_provenance(data_dir: Optional[str] = None) -> Dict[str, Any]:
    """Policy version and the commit it was generated from, best effort."""
    if data_dir is None:
        data_dir = os.path.dirname(DEFAULT_PATH)
    path = os.path.join(data_dir, "inference_policy.json")
    try:
        with open(path, "r", encoding="utf-8") as f:
            pol = json.load(f)
        return {
            "policy_version": pol.get("policy_version"),
            "policy_code_commit": pol.get("policy_code_commit"),
            "policy_regenerated_by": pol.get("regenerated_by"),
        }
    except (OSError, ValueError, AttributeError):
        return {"policy_version": None, "policy_code_commit": None,
                "policy_regenerated_by": None}


def _model_provenance(bundle_dir: Optional[str] = None) -> Dict[str, Any]:
    """Model identity: bundle, checkpoint trained-at, seed. Best effort."""
    out: Dict[str, Any] = {"bundle": None, "checkpoint_trained_at": None,
                           "seed": None}
    if bundle_dir is None:
        data_dir = os.path.dirname(DEFAULT_PATH)
        bundle_dir = os.path.join(data_dir, "bundles")
    try:
        manifest = os.path.join(bundle_dir, "bundle_manifest.json")
        with open(manifest, "r", encoding="utf-8") as f:
            m = json.load(f)
        out["bundle"] = m.get("bundle_id") or m.get("bundle") or os.path.basename(bundle_dir)
        hashes = m.get("artifact_hashes") or m.get("hashes") or {}
        for key in ("model_checkpoint", "checkpoint", "weights"):
            if isinstance(hashes, dict) and key in hashes:
                out["checkpoint_sha256"] = hashes[key]
                break
        trained = m.get("model_trained_at") or m.get("trained_at")
        if trained:
            out["checkpoint_trained_at"] = trained
    except (OSError, ValueError, AttributeError):
        pass
    return out


class PredictionAudit:
    """Append-only JSONL writer. Safe to call from any thread."""

    def __init__(self, path: Optional[str] = None, max_bytes: int = MAX_BYTES,
                 keep: int = KEEP_GENERATIONS, data_dir: Optional[str] = None):
        self.path = path if path is not None else os.environ.get(
            "PREDICTION_AUDIT_PATH", DEFAULT_PATH)
        self.max_bytes = int(max_bytes)
        self.keep = max(1, int(keep))
        self.data_dir = data_dir or os.path.dirname(DEFAULT_PATH)
        self._lock = threading.Lock()
        self._prov = {"at": 0.0, "value": {}}
        self.errors = 0
        self.written = 0

    # ---- provenance cache ---------------------------------------------
    def _provenance(self) -> Dict[str, Any]:
        now = time.monotonic()
        with self._lock:
            if self._prov["at"] and (now - self._prov["at"]) < PROVENANCE_TTL_SECONDS:
                return self._prov["value"]
        value = {
            "policy": _policy_provenance(self.data_dir),
            "model": _model_provenance(os.path.join(self.data_dir, "bundles")),
        }
        with self._lock:
            self._prov = {"at": now, "value": value}
        return value

    def _bundle_for(self, horizon_hours: Any) -> Optional[str]:
        try:
            h = int(round(float(horizon_hours)))
        except (TypeError, ValueError):
            return None
        return f"h{h}"

    # ---- rotation ------------------------------------------------------
    def _rotate_if_needed(self) -> None:
        try:
            if not os.path.exists(self.path):
                return
            if os.path.getsize(self.path) < self.max_bytes:
                return
        except OSError:
            return
        for i in range(self.keep - 1, 0, -1):
            src = f"{self.path}.{i}"
            dst = f"{self.path}.{i + 1}"
            try:
                if os.path.exists(src):
                    os.replace(src, dst)
            except OSError:
                continue
        try:
            os.replace(self.path, f"{self.path}.1")
        except OSError:
            pass

    # ---- the record ----------------------------------------------------
    def build_record(
        self,
        station_id: str,
        horizon_hours: Any,
        forecast: Dict[str, Any],
        origin_timestamp: Optional[str] = None,
        device_id: Optional[str] = None,
        variables: Optional[Dict[str, Any]] = None,
        nwp: Optional[Dict[str, Any]] = None,
        sensor_health: Optional[Dict[str, Any]] = None,
        extra: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """
        Assemble one audit record. Pure; safe to call without writing.
        """
        prov = self._provenance()
        bundle = self._bundle_for(horizon_hours)
        model = dict(prov["model"])
        model["bundle"] = bundle or model.get("bundle")

        record: Dict[str, Any] = {
            "schema_version": SCHEMA_VERSION,
            "record_id": _make_id(station_id, origin_timestamp, horizon_hours),
            "recorded_at_utc": _utc_now(),
            "origin_timestamp_utc": origin_timestamp,
            "station_id": station_id,
            "device_id": device_id,
            "horizon_hours": _finite(horizon_hours),
            "provenance": {
                "model": model,
                "policy": prov["policy"],
                "nwp": nwp or {"applied": False, "reason": "not supplied"},
            },
            "variables": variables or {},
            "sensor_health": sensor_health,
        }
        if extra:
            record["extra"] = extra
        # Keep the raw forecast too, so an auditor does not have to trust the
        # per-variable extraction above.
        record["forecast_raw"] = {k: v for k, v in (forecast or {}).items()
                                  if isinstance(v, (int, float, str, bool, type(None)))}
        return record

    def write(self, record: Dict[str, Any]) -> bool:
        """Append one record. Returns True on success; never raises."""
        try:
            line = json.dumps(record, ensure_ascii=False, default=str)
        except Exception as exc:  # noqa: BLE001
            # Must be broad. `default=str` falls back to __repr__ for objects
            # that define neither, and a __repr__ that raises RuntimeError (or
            # anything else) would otherwise escape and take the forecast with
            # it. Catching only TypeError/ValueError let that through.
            self.errors += 1
            fallback = {
                "schema_version": SCHEMA_VERSION,
                "recorded_at_utc": _utc_now(),
                "station_id": record.get("station_id"),
                "horizon_hours": record.get("horizon_hours"),
                "write_error": f"{type(exc).__name__}: {exc}",
            }
            try:
                line = json.dumps(fallback)
            except Exception:  # noqa: BLE001
                self.errors += 1
                return False
        with self._lock:
            try:
                os.makedirs(os.path.dirname(self.path) or ".", exist_ok=True)
                self._rotate_if_needed()
                with open(self.path, "a", encoding="utf-8", newline="\n") as f:
                    f.write(line + "\n")
                self.written += 1
                return True
            except OSError:
                self.errors += 1
                return False
            except Exception:  # noqa: BLE001
                self.errors += 1
                return False

    def record(self, **kwargs: Any) -> bool:
        """Build and write in one call, guarded end to end."""
        try:
            return self.write(self.build_record(**kwargs))
        except Exception:  # noqa: BLE001 - the trail must never break a forecast
            self.errors += 1
            return False

    def status(self) -> Dict[str, Any]:
        size = None
        try:
            size = os.path.getsize(self.path)
        except OSError:
            pass
        return {"path": self.path, "exists": size is not None,
                "bytes": size, "written": self.written, "errors": self.errors,
                "max_bytes": self.max_bytes, "keep": self.keep}


_AUDIT: Optional[PredictionAudit] = None
_AUDIT_LOCK = threading.Lock()


def get_audit(path: Optional[str] = None) -> PredictionAudit:
    global _AUDIT
    with _AUDIT_LOCK:
        if _AUDIT is None or (path is not None and _AUDIT.path != path):
            _AUDIT = PredictionAudit(path)
        return _AUDIT


def read_records(path: Optional[str] = None, limit: Optional[int] = None,
                 station_id: Optional[str] = None,
                 since: Optional[str] = None) -> List[Dict[str, Any]]:
    """
    Read the trail back. Tolerant of a truncated final line, which is what a
    crash mid-append looks like.
    """
    target = path or os.environ.get("PREDICTION_AUDIT_PATH", DEFAULT_PATH)
    out: List[Dict[str, Any]] = []
    try:
        with open(target, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                if not isinstance(rec, dict):
                    continue
                if station_id is not None and rec.get("station_id") != station_id:
                    continue
                if since is not None and str(rec.get("recorded_at_utc") or "") < since:
                    continue
                out.append(rec)
    except OSError:
        return []
    if limit is not None:
        return out[-limit:]
    return out


def variable_entry(value: Any, producer: str, nwp_raw: Any = None,
                   nwp_corrected: Any = None) -> Dict[str, Any]:
    """One published variable, with the provenance needed to reproduce it."""
    return {
        "value": _finite(value),
        "producer": producer,
        "nwp_raw": _finite(nwp_raw),
        "nwp_corrected": _finite(nwp_corrected),
    }

class ObservationAudit(PredictionAudit):
    """
    Append-only trail of the observations themselves.

    Separate file from the prediction trail so the two can be rotated and read
    independently, but built on the same writer so both inherit the same two
    guarantees: never break the caller, never lose a line.
    """

    def build_record(
        self,
        station_id: str,
        observed_at_utc: Optional[str] = None,
        device_id: Optional[str] = None,
        telemetry: Optional[Dict[str, Any]] = None,
        **_: Any,
    ) -> Dict[str, Any]:
        t = telemetry or {}
        return {
            "schema_version": SCHEMA_VERSION,
            "record_id": _make_id(station_id, observed_at_utc, "obs"),
            "recorded_at_utc": _utc_now(),
            "observed_at_utc": observed_at_utc,
            "station_id": station_id,
            "device_id": device_id,
            "telemetry": {
                k: _finite(v) for k, v in t.items()
                if k not in ("qc_status", "topic")
            },
        }


_OBS: Optional[ObservationAudit] = None


def get_observation_audit(path: Optional[str] = None) -> ObservationAudit:
    global _OBS
    with _AUDIT_LOCK:
        if _OBS is None or (path is not None and _OBS.path != path):
            target = path or os.environ.get(
                "OBSERVATION_AUDIT_PATH",
                os.path.join(os.path.dirname(DEFAULT_PATH), "observation_audit.jsonl"))
            _OBS = ObservationAudit(path=target)
        return _OBS


def read_observations(path: Optional[str] = None, station_id: Optional[str] = None,
                      since: Optional[str] = None,
                      until: Optional[str] = None) -> List[Dict[str, Any]]:
    """Read the observation trail back, same tolerance as read_records."""
    target = path or os.environ.get(
        "OBSERVATION_AUDIT_PATH",
        os.path.join(os.path.dirname(DEFAULT_PATH), "observation_audit.jsonl"))
    out: List[Dict[str, Any]] = []
    try:
        with open(target, "r", encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                if not isinstance(rec, dict):
                    continue
                if station_id is not None and rec.get("station_id") != station_id:
                    continue
                ts = str(rec.get("observed_at_utc") or "")
                if since is not None and ts < since:
                    continue
                if until is not None and ts > until:
                    continue
                out.append(rec)
    except OSError:
        return []
    return out
